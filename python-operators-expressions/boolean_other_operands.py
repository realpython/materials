# The and operator returns one of its operands
print(3 and 4)
print(0 and 4)
print(3 and 0)

# The or operator also returns one of its operands
print(3 or 4)
print(0 or 4)
print(3 or 0)

# When both operands are falsy, or returns the right-hand one
print(0 or [])

# The not operator always returns a Boolean value
print(not 3)
print(not 0)
