a = 5
b = 2

print(+a)
print(-b)
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a // b)
print(a**b)

# The division operator always returns a floating-point number
print(10 / 5)
print(10.0 / 5)

# With complex numbers, division returns a complex number
print(10 / 5j)

# Floor division always rounds down
print(10 // 4)
print(-10 // -4)

print(10 // -4)
print(-10 // 4)
